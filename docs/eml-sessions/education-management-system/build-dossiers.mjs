#!/usr/bin/env node
/**
 * Emits one dossier per entity (llmdetailed.txt §10.4) from the model itself,
 * so the specification and the document cannot drift: the field table, enums,
 * relationships, lifecycle, rules, hooks and access are read out of the `.mmd`,
 * and only the judgement sections — placement, cross-entity effects and the
 * open questions — are authored here.
 *
 *   node build-dossiers.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "education-management-system.mmd"), "utf8");
const lines = src.split("\n");

const entities = new Map();
{
  let current = null;
  for (const line of lines) {
    const open = line.match(/^ {4}(\w+) \{$/);
    if (open) {
      current = { name: open[1], attributes: [] };
      entities.set(open[1], current);
      continue;
    }
    if (current && /^ {4}\}$/.test(line)) {
      current = null;
      continue;
    }
    if (current) {
      const [type, name, ...modifiers] = line.trim().split(/\s+/);
      if (name) current.attributes.push({ type, name, modifiers });
    }
  }
}

const read = (pattern) => lines.map((l) => l.trim().match(pattern)).filter(Boolean);

const entityHelp = new Map(read(/^%%entity (\w+) help: (.*)$/).map((m) => [m[1], m[2]]));
const parents = new Map(read(/^%%entity (\w+) parent: (\w+)$/).map((m) => [m[1], m[2]]));
const fieldHelp = new Map(read(/^%%field (\w+)\.(\w+) help: (.*)$/).map((m) => [`${m[1]}.${m[2]}`, m[3]]));
const fieldEnum = new Map(read(/^%%field (\w+)\.(\w+) enum: (\w+)$/).map((m) => [`${m[1]}.${m[2]}`, m[3]]));
const enums = new Map(read(/^%%enum (\w+): (.*)$/).map((m) => [m[1], m[2]]));
const relationships = read(/^(\w+)\s+(\S+)\s+(\w+)\s+: "(.*)"$/).map((m) => ({
  source: m[1], operator: m[2], target: m[3], label: m[4],
}));
const indexes = read(/^%%index (\w+)\((.*)\)$/).map((m) => ({ entity: m[1], columns: m[2] }));
const rbac = read(/^%%rbac role:(\S+) on (\w+)\.(\w+)$/).map((m) => ({ roles: m[1], entity: m[2], op: m[3] }));
const hooks = read(/^%%hook (\w+) (\w+) on (\w+)$/).map((m) => ({ event: m[1], handler: m[2], entity: m[3] }));

const machines = new Map();
for (const match of src.matchAll(/%%workflow (\w+) entity: (\w+) kind: state\nstateDiagram-v2\n([\s\S]*?)\n\n/g)) {
  machines.set(match[2], { name: match[1], body: match[3].replace(/\n+$/, "") });
}

const sagas = [];
for (const match of src.matchAll(/%%workflow (\w+) entity: (\w+) kind: saga([^\n]*)\nflowchart TD\n([\s\S]*?)(?=\n%% ----|\n%%meta|$)/g)) {
  sagas.push({ name: match[1], entity: match[2], steps: match[4].split("\n").filter((l) => l.trim().startsWith("%%step")) });
}

const rules = [];
for (const match of src.matchAll(/%%rule (\w+) on (\w+) event: (\w+) priority: (\d+)\n([\s\S]*?)(?=\n%%meta|\n%% ----|$)/g)) {
  rules.push({
    name: match[1], entity: match[2], event: match[3],
    actions: match[5].split("\n").map((l) => l.trim()).filter((l) => l.startsWith("%%action")),
  });
}

/** The judgement sections — authored, not derived. */
const judgement = JSON.parse(readFileSync(join(here, "dossier-notes.json"), "utf8"));

mkdirSync(join(here, "entities"), { recursive: true });

for (const [name, entity] of entities) {
  const notes = judgement[name] ?? {};
  const parent = parents.get(name);
  const out = [];
  const category = (lines.find((l) => l.trim().startsWith("%%category") && new RegExp(`\\b${name}\\b`).test(l)) ?? "")
    .match(/name: ([^;]+);/);

  out.push(`# ${name}  ·  ${parent ? `child of ${parent}` : "standalone"}${category ? `  ·  category: ${category[1]}` : ""}`);
  out.push("");
  out.push(`**Role.** ${entityHelp.get(name) ?? "—"}`);
  out.push("");
  out.push(`**Placement.** ${notes.placement ?? "—"}`);
  out.push("");

  out.push("## Fields");
  out.push("");
  out.push("| Column | Type | Modifiers | Purpose |");
  out.push("|---|---|---|---|");
  for (const attribute of entity.attributes) {
    out.push(`| \`${attribute.name}\` | ${attribute.type} | ${attribute.modifiers.join(" ") || "—"} | ${fieldHelp.get(`${name}.${attribute.name}`) ?? (attribute.modifiers.includes("PK") ? "The record's own identifier. Generated by the application and never keyed; it is never shown as a display value." : "**no help text**")} |`);
  }
  out.push("");

  const bound = entity.attributes.filter((a) => fieldEnum.has(`${name}.${a.name}`));
  out.push("## Enums");
  out.push("");
  out.push(bound.length
    ? bound.map((a) => `- \`${a.name}\` → **${fieldEnum.get(`${name}.${a.name}`)}**: ${enums.get(fieldEnum.get(`${name}.${a.name}`))}`).join("\n")
    : "None — this entity carries no coded column.");
  out.push("");

  out.push("## Relationships");
  out.push("");
  const related = relationships.filter((r) => r.source === name || r.target === name);
  out.push(related.length
    ? related.map((r) => `- \`${r.source} ${r.operator} ${r.target}\` — ${r.label}${r.target === name ? " *(this side carries the foreign key)*" : ""}`).join("\n")
    : "None.");
  out.push("");
  const entityIndexes = indexes.filter((i) => i.entity === name);
  if (entityIndexes.length) {
    out.push(`**Indexes.** ${entityIndexes.map((i) => `\`${i.entity}(${i.columns})\``).join(" · ")}`);
    out.push("");
  }

  out.push("## Lifecycle");
  out.push("");
  if (machines.has(name)) {
    out.push(`\`%%workflow ${machines.get(name).name} entity: ${name} kind: state\` — every edge below is enforced by the generated entity-access guard, for every caller including the master role.`);
    out.push("");
    out.push("```");
    out.push(machines.get(name).body.replace(/^ {4}/gm, ""));
    out.push("```");
  } else {
    out.push(notes.lifecycle ?? "None. This entity has no status column and no lifecycle.");
  }
  out.push("");

  out.push("## Rules");
  out.push("");
  const entityRules = rules.filter((r) => r.entity === name);
  if (entityRules.length) {
    for (const rule of entityRules) {
      const form = rule.actions.length ? "**`%%action` decision table — it can act**" : "**node graph — it decides only, and cannot act**";
      out.push(`### \`${rule.name}\` on \`${rule.event}\` — ${form}`);
      out.push("");
      out.push(rule.actions.length ? rule.actions.map((a) => `- \`${a.replace(/^%%action /, "")}\``).join("\n") : "No outputs: the engine finds no actions, by design (§3.4).");
      out.push("");
    }
  } else {
    out.push("None on this entity.");
    out.push("");
  }

  out.push("## Hooks");
  out.push("");
  const entityHooks = hooks.filter((h) => h.entity === name);
  out.push(entityHooks.length
    ? entityHooks.map((h) => `- \`${h.event}\` → \`${h.handler}\``).join("\n")
    : "None.");
  out.push("");

  out.push("## Cross-entity effects");
  out.push("");
  out.push(notes.crossEntity ?? "None — writing this entity never has to write another.");
  out.push("");
  const involved = sagas.filter((s) => s.entity === name || s.steps.some((step) => step.includes(`entity: ${name}`)));
  if (involved.length) {
    out.push("Sagas that touch it:");
    out.push("");
    for (const saga of involved) {
      out.push(`- **${saga.name}**${saga.entity === name ? " *(triggered on this entity)*" : ""}`);
      for (const step of saga.steps) out.push(`  - \`${step.trim().replace(/^%%step /, "")}\``);
    }
    out.push("");
  }

  out.push("## Access");
  out.push("");
  const entityRbac = rbac.filter((r) => r.entity === name);
  out.push("| Operation | Roles |");
  out.push("|---|---|");
  for (const rule of entityRbac) out.push(`| \`${rule.op}\` | ${rule.roles.split("|").join(" · ")} |`);
  out.push("");
  if (!entityRbac.some((r) => r.op === "read")) out.push("> **No `read` rule — this entity is visible to every signed-in caller.**\n");

  out.push("## Open questions");
  out.push("");
  out.push(notes.openQuestions ?? "None outstanding.");
  out.push("");

  writeFileSync(join(here, "entities", `${name}.md`), `${out.join("\n")}`);
}

console.log(`wrote ${entities.size} dossiers`);
