/**
 * The move-fact pattern, and how a model sheds it.
 *
 * Before records moved by action buttons, a model could not let a person change a
 * state, so every move was spelled out by hand: a `<state>_at` column a person
 * filled in, an `<Entity>StateProgress` rule whose rows started one saga per
 * move, and an `<Entity><State>Move` saga whose steps wrote the state and cleared
 * the other `_at` columns. A migration wrote that pattern into every model — about
 * six hundred sagas across the published ones.
 *
 * A button press is the move now (`language/state-field.ts`), so those rules and
 * sagas would move a record a second time, behind the button's back. The checker
 * reports them (EML512) and the fixer removes them. `_at` columns stay: the
 * application stamps them when a record reaches the state, so the help text
 * written for the old pattern is rewritten to say so.
 *
 * Recognised by shape, never by name alone. A saga is retired only when every
 * step is an `UpdateEntity` of its own entity that writes the state field or
 * clears an `_at` column; a rule only when every action starts one of those
 * sagas. Anything an author added to either keeps the whole section in the model.
 *
 * Pure — no `node:` imports — so the browser bundles carry it too.
 */

/** One section of a model the fixer removes, as 0-based line indices `[start, end)`. */
export interface RetiredSection {
  kind: "saga" | "rule";
  name: string;
  entity: string;
  /** 1-based line of the `%%workflow` / `%%rule` directive, for a diagnostic. */
  line: number;
  start: number;
  end: number;
}

/** One line whose stock help the fixer rewrites. */
export interface StockHelpRewrite {
  /** 1-based line number. */
  line: number;
  replacement: string;
}

export interface RetiredMoves {
  sections: RetiredSection[];
  rewrites: StockHelpRewrite[];
}

const SAGA = /^%%workflow\s+(\w+)\s+entity:\s*(\w+)\s+kind:\s*saga\b.*\btrigger:\s*rule\b/;
const RULE = /^%%rule\s+(\w+)\s+on\s+(\w+)\b/;
const STEP = /^%%step\s+\w+\s+(\w+)\b(.*)$/;
const ACTION = /^%%action\s+\w+\s+trigger-workflow\b.*\bworkflow:\s*(\w+)\s*$/;
/** A line that opens the next section: the block before it ends there. */
const SECTION_START =
  /^(?:%%(?:meta\s+name:|workflow\b|rule\b|field\b|section\b|rbac\b|report\b|entity\b|enum\b|category\b|index\b|hook\b|jdm-graph\b)|%% -{2,}|erDiagram\b|stateDiagram(?:-v2)?\b)/;

const FIELD_HELP =
  /^(\s*%%field\s+\w+\.\w+_at\s+help:\s*)When the move to (.+?) was recorded on this (.+?)\. Recording it moves .+?: the workflows set the status, which nobody changes by hand\.\s*$/;
const SECTION_HELP =
  /help: The times that move this (.+?) along its lifecycle\. Recording one is how its status changes; the status itself is shown in the header\./;
const HEADER = [
  "%% ---- The state field is system-managed: each move is a rule and a saga ----",
  "%% Nobody changes a state by hand. Recording the time a move depends on starts",
  "%% the saga that sets the state; generated by the state-rule migration.",
];
const HEADER_NOW = [
  "%% ---- When each status was reached: stamped by the application ----",
  "%% A record moves by an action button, along an edge its state diagram draws,",
  "%% and the application writes the <state>_at time when it does.",
];

function propsOf(rest: string): Record<string, string> {
  const props: Record<string, string> = {};
  for (const m of rest.matchAll(/(\w+):\s*(\S+)/g)) props[m[1]!] = m[2]!;
  return props;
}

/** Where a section that starts at `index` ends: before the next section. */
function blockEnd(lines: string[], index: number): number {
  let end = index + 1;
  while (end < lines.length && !SECTION_START.test(lines[end]!.trim())) end++;
  return end;
}

/** Back up over the `%%meta name:` / `%%meta kind:` lines that introduce a section. */
function blockStart(lines: string[], index: number): number {
  let start = index;
  while (start > 0 && /^%%meta\s+(?:name|kind):/.test(lines[start - 1]!.trim())) start--;
  return start;
}

/**
 * Find the retired move rules and sagas in a model, and the stock help to rewrite.
 *
 * @param stateFieldOf the state field of an entity with a state machine, else undefined
 */
export function findRetiredMoves(
  source: string,
  stateFieldOf: (entity: string) => string | undefined
): RetiredMoves {
  const lines = source.split("\n");
  const sections: RetiredSection[] = [];
  const retiredSagas = new Set<string>();

  // Sagas first: a rule is retired only when every saga it starts is.
  for (let i = 0; i < lines.length; i++) {
    const saga = SAGA.exec(lines[i]!.trim());
    if (!saga) continue;
    const [, name = "", entity = ""] = saga;
    const field = stateFieldOf(entity);
    if (!field) continue;
    const end = blockEnd(lines, i);
    let writesState = 0;
    let other = false;
    for (let j = i + 1; j < end; j++) {
      const step = STEP.exec(lines[j]!.trim());
      if (!step) continue;
      const [, type = "", rest = ""] = step;
      const props = propsOf(rest);
      const ownEntity = !props.entity || props.entity === entity;
      if (type === "UpdateEntity" && ownEntity && props.field === field && props.value) {
        writesState++;
      } else if (
        type === "UpdateEntity" &&
        ownEntity &&
        /_at$/.test(props.field ?? "") &&
        props.value === "null"
      ) {
        // Clearing the next move's fact: part of the same pattern.
      } else {
        other = true;
      }
    }
    if (writesState === 1 && !other) {
      retiredSagas.add(name);
      sections.push({ kind: "saga", name, entity, line: i + 1, start: blockStart(lines, i), end });
    }
  }

  for (let i = 0; i < lines.length; i++) {
    const rule = RULE.exec(lines[i]!.trim());
    if (!rule) continue;
    const [, name = "", entity = ""] = rule;
    const end = blockEnd(lines, i);
    let actions = 0;
    let other = false;
    for (let j = i + 1; j < end; j++) {
      const text = lines[j]!.trim();
      if (!text.startsWith("%%action")) continue;
      actions++;
      const action = ACTION.exec(text);
      if (!action || !retiredSagas.has(action[1]!)) other = true;
    }
    if (actions > 0 && !other) {
      sections.push({ kind: "rule", name, entity, line: i + 1, start: blockStart(lines, i), end });
    }
  }

  const rewrites: StockHelpRewrite[] = [];
  lines.forEach((text, index) => {
    const field = FIELD_HELP.exec(text);
    if (field) {
      const [, head = "", state = "", noun = ""] = field;
      rewrites.push({
        line: index + 1,
        replacement: `${head}When this ${noun} moved to ${state}. Stamped by the application when the move is made; nobody types it.`,
      });
      return;
    }
    const section = SECTION_HELP.exec(text);
    if (section) {
      rewrites.push({
        line: index + 1,
        replacement: text.replace(
          SECTION_HELP,
          `help: When this ${section[1]} reached each status, stamped by the application as the record moves; the status itself is shown in the header.`
        ),
      });
      return;
    }
    const header = HEADER.indexOf(text.trim());
    if (header >= 0) {
      rewrites.push({
        line: index + 1,
        replacement: text.replace(HEADER[header]!, HEADER_NOW[header]!),
      });
    }
  });

  sections.sort((a, b) => a.start - b.start);
  return { sections, rewrites };
}

/**
 * The lines `[start, end)` of the section whose `%%workflow` / `%%rule` directive is
 * at `index`, with the `%%meta` lines that introduce it — what the fixer removes for
 * one EML512, working bottom-up so no other fix's line moves.
 */
export function sectionSpan(lines: string[], index: number): { start: number; end: number } | undefined {
  const text = lines[index]?.trim() ?? "";
  if (!SAGA.test(text) && !RULE.test(text)) return undefined;
  return { start: blockStart(lines, index), end: blockEnd(lines, index) };
}

/**
 * Rewrite, in place, the help the move-fact pattern wrote: the `<state>_at` columns
 * and their Progress sections now record when the application moved the record.
 * No line is added or removed. Returns how many lines changed.
 */
export function rewriteStockHelp(lines: string[]): number {
  const { rewrites } = findRetiredMoves(lines.join("\n"), () => undefined);
  for (const rewrite of rewrites) lines[rewrite.line - 1] = rewrite.replacement;
  return rewrites.length;
}

/** The model with its retired move rules and sagas removed and their help rewritten. */
export function retireMoves(
  source: string,
  stateFieldOf: (entity: string) => string | undefined
): { source: string; removed: RetiredSection[]; rewritten: number } {
  const { sections, rewrites } = findRetiredMoves(source, stateFieldOf);
  const lines = source.split("\n");
  for (const rewrite of rewrites) lines[rewrite.line - 1] = rewrite.replacement;
  const drop = new Set<number>();
  for (const section of sections) {
    for (let i = section.start; i < section.end; i++) drop.add(i);
  }
  // A block runs up to the next section, so it takes its own trailing blank lines
  // with it and the document's spacing elsewhere is untouched.
  const kept = lines.filter((_, index) => !drop.has(index));
  return { source: kept.join("\n"), removed: sections, rewritten: rewrites.length };
}
